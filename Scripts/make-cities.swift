#!/usr/bin/env swift
// Builds Sources/Kit/Resources/cities.tsv, the city table behind the widget's picker, from the
// GeoNames dump. The OS knows only time zones, not the cities inside them, so the table maps each
// city to its IANA zone. Run `make cities` to download the dump and run this script.
//
// Usage: Scripts/make-cities.swift <cities15000.txt> <admin1CodesASCII.txt> <output.tsv>

import Foundation

let arguments = CommandLine.arguments
guard arguments.count == 4 else {
    FileHandle.standardError.write(Data("usage: make-cities.swift <cities.txt> <admin1.txt> <out.tsv>\n".utf8))
    exit(64)
}

func lines(_ path: String) throws -> [Substring] {
    try String(contentsOfFile: path, encoding: .utf8).split(separator: "\n")
}

func fields(_ line: Substring) -> [Substring] {
    line.split(separator: "\t", omittingEmptySubsequences: false)
}

func folded(_ string: some StringProtocol) -> String {
    string.folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
}

// "US.WA" → "Washington"
var admin1: [Substring: Substring] = [:]
for line in try lines(arguments[2]) {
    let f = fields(line)
    if f.count >= 3 { admin1[f[0]] = f[2] }
}

// Sections of a city, and historical, abandoned or destroyed places, are not cities to pick.
let excludedFeatureCodes: Set<Substring> = ["PPLX", "PPLH", "PPLQ", "PPLW"]

struct Row {
    let name: Substring
    let asciiName: Substring
    let admin: Substring
    let country: Substring
    let tzid: Substring
    let population: Int
}

var rows: [Row] = []
var dropped: [Substring: Int] = [:]
for line in try lines(arguments[1]) {
    // geonameid, name, asciiname, alternatenames, latitude, longitude, feature class,
    // feature code, country code, cc2, admin1 … admin4, population, elevation, dem, timezone, …
    let f = fields(line)
    guard f.count >= 18, !excludedFeatureCodes.contains(f[7]) else { continue }
    let tzid = f[17]
    guard TimeZone(identifier: String(tzid)) != nil else {
        dropped[tzid, default: 0] += 1
        continue
    }
    rows.append(Row(
        name: f[1],
        asciiName: f[2],
        admin: admin1["\(f[8]).\(f[10])"] ?? "",
        country: f[8],
        tzid: tzid,
        population: Int(f[14]) ?? 0
    ))
}

rows.sort {
    $0.population != $1.population
        ? $0.population > $1.population
        : $0.name.localizedStandardCompare($1.name) == .orderedAscending
}

var output = """
# City data from GeoNames (https://www.geonames.org), licensed under CC BY 4.0
# (https://creativecommons.org/licenses/by/4.0/). Generated by Scripts/make-cities.swift; do not edit.
# name, ASCII name (only when search folding cannot reach it), admin1, ISO country, IANA tzid, population

"""
for row in rows {
    // The ASCII name only helps search when diacritic folding does not already produce it (Łódź).
    let ascii = folded(row.asciiName) == folded(row.name) ? "" : row.asciiName
    output += [row.name, ascii, row.admin, row.country, row.tzid, Substring(String(row.population))]
        .joined(separator: "\t") + "\n"
}
try output.write(toFile: arguments[3], atomically: true, encoding: .utf8)

print("✓ \(rows.count) cities → \(arguments[3])")
for (tzid, count) in dropped.sorted(by: { $0.key < $1.key }) {
    print("• dropped \(count) with a zone the OS does not know: \(tzid)")
}
